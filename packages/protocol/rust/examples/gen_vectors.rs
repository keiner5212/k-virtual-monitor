//! Prints the golden vectors used by both implementations of the protocol.
//!
//! Run with `cargo run --example gen_vectors` from `packages/protocol/rust`,
//! and write the output to `packages/protocol/testdata/vectors.json`.

use kvm_protocol::crypto::{derive_session_keys, proof, Psk};
use kvm_protocol::frame::MessageType;
use kvm_protocol::handshake::{client_transcript, server_transcript};
use kvm_protocol::session::Session;

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn main() {
    let psk = Psk::from_bytes([0x11; 32]);
    let client_nonce = [0x22; 32];
    let server_nonce = [0x33; 32];
    let device_id = [0x44; 16];

    let keys = derive_session_keys(&psk, &client_nonce, &server_nonce);
    let client_proof = proof(
        &psk,
        b"kvm-auth-v1|c2s",
        &client_transcript(&client_nonce, &server_nonce, &device_id),
    );
    let server_proof = proof(
        &psk,
        b"kvm-auth-v1|s2c",
        &server_transcript(&client_nonce, &server_nonce),
    );

    let mut session = Session::client(keys.clone());
    let (header, sealed) = session
        .seal(MessageType::Frame, 0, b"kvm golden frame")
        .expect("seal");

    let json = serde_json::json!({
        "version": 1,
        "note": "Generated by `cargo run --example gen_vectors`. Both the Rust and the TypeScript implementation must reproduce these values.",
        "psk": hex(psk.as_bytes()),
        "clientNonce": hex(&client_nonce),
        "serverNonce": hex(&server_nonce),
        "deviceId": hex(&device_id),
        "clientProof": hex(&client_proof),
        "serverProof": hex(&server_proof),
        "sessionKeyC2s": hex(keys.client_to_server.as_bytes()),
        "sessionKeyS2c": hex(keys.server_to_client.as_bytes()),
        "sealedFrame": {
            "type": header.kind as u8,
            "flags": header.flags,
            "seq": header.seq,
            "header": hex(&header.encode()),
            "payload": hex(&sealed),
            "plaintext": hex(b"kvm golden frame"),
        }
    });

    println!("{}", serde_json::to_string_pretty(&json).expect("json"));
}
